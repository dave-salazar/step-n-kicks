-- Shipping rule: free from PHP 5,000, otherwise PHP 150.   (keep in sync with SNKRules in cart.js)
-- Voucher: PHP 500 off a signed-in customer's first (non-cancelled) order.
create function public.place_order(p_items jsonb, p_payment text, p_customer jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_admin boolean := public.is_admin();
  v_pay text := lower(coalesce(p_payment, 'cod'));
  v_name text  := left(nullif(trim(p_customer ->> 'name'), ''), 80);
  v_phone text := left(nullif(trim(p_customer ->> 'phone'), ''), 20);
  v_addr text  := left(nullif(trim(p_customer ->> 'address_line'), ''), 200);
  v_city text  := left(nullif(trim(p_customer ->> 'city'), ''), 80);
  v_prov text  := left(nullif(trim(p_customer ->> 'province'), ''), 80);
  v_zip text   := left(nullif(trim(p_customer ->> 'postal_code'), ''), 10);
  it jsonb; prod public.products%rowtype; v_qty int; v_size text;
  v_sub numeric := 0; v_ship numeric; v_disc numeric := 0; v_total numeric;
  v_id text; v_tok uuid;
begin
  if v_uid is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'EMPTY_ORDER';
  end if;
  if v_pay not in ('cod', 'gcash', 'maya') then raise exception 'BAD_PAYMENT'; end if;
  -- Online payments are not live yet: customers can only use cash on delivery.
  -- (Admins may record GCash/Maya for manual orders.)  Remove this line when payments go live.
  if not v_admin and v_pay <> 'cod' then raise exception 'PAYMENT_UNAVAILABLE'; end if;

  if not v_admin then
    if v_name is null or v_phone is null or v_addr is null or v_city is null or v_prov is null then
      raise exception 'ADDRESS_REQUIRED';
    end if;
    if v_phone !~ '^[0-9+() -]{7,20}$' then raise exception 'BAD_PHONE'; end if;
    if (select count(*) from public.orders where user_id = v_uid and status = 'pending') >= 5 then
      raise exception 'TOO_MANY_PENDING';
    end if;
  end if;

  loop
    v_id := 'SNK-' || lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
    exit when not exists (select 1 from public.orders where id = v_id);
  end loop;

  insert into public.orders (id, payment, shipping, discount, total, customer_name, customer_phone,
                             customer_email, address_line, city, province, postal_code, user_id)
  values (v_id, v_pay, 0, 0, 0, coalesce(v_name, 'Guest'), v_phone,
          case when v_admin then null else auth.jwt() ->> 'email' end,
          v_addr, v_city, v_prov, v_zip, case when v_admin then null else v_uid end)
  returning cancel_token into v_tok;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty  := greatest(1, least(10, coalesce((it ->> 'qty')::int, 1)));
    v_size := coalesce(it ->> 'size', '9');
    if v_size not in ('6','7','8','9','10','11','12','13') then raise exception 'BAD_SIZE'; end if;
    update public.products set stock = stock - v_qty
     where status = 'active' and stock >= v_qty
       and ((it ->> 'id' is not null and id::text = it ->> 'id')
         or (it ->> 'id' is null and lower(name) = lower(it ->> 'n')))
    returning * into prod;
    if not found then raise exception 'OUT_OF_STOCK:%', coalesce(it ->> 'n', it ->> 'id'); end if;
    insert into public.order_items (order_id, product_id, name, brand, size, qty, price)
    values (v_id, prod.id::text, prod.name, prod.brand, v_size, v_qty, prod.price);
    v_sub := v_sub + prod.price * v_qty;
  end loop;

  v_ship := case when v_sub >= 5000 then 0 else 150 end;
  if not v_admin and not exists (
       select 1 from public.orders where user_id = v_uid and status <> 'cancelled' and id <> v_id) then
    v_disc := least(500, v_sub);
  end if;
  v_total := greatest(0, v_sub + v_ship - v_disc);
  update public.orders set shipping = v_ship, discount = v_disc, total = v_total where id = v_id;
  return jsonb_build_object('id', v_id, 'subtotal', v_sub, 'shipping', v_ship, 'discount', v_disc, 'total', v_total);
end $$;

-- A customer can cancel their own order while it is still 'pending'; stock goes back.
create function public.cancel_order(p_id text) returns void
language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype;
begin
  select * into o from public.orders where id = p_id and user_id = auth.uid() for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if o.status <> 'pending' then raise exception 'NOT_CANCELLABLE'; end if;
  update public.products p set stock = p.stock + a.q
    from (select product_id, sum(qty)::int q from public.order_items where order_id = p_id group by product_id) a
   where p.id::text = a.product_id;
  update public.orders set status = 'cancelled' where id = p_id;
end $$;

-- Admin-only status changes (restocks on cancel, re-reserves on un-cancel).
create or replace function public.set_order_status(p_id text, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN'; end if;
  if p_status not in ('pending','paid','shipped','delivered','cancelled') then raise exception 'BAD_STATUS'; end if;
  select * into o from public.orders where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if o.status <> 'cancelled' and p_status = 'cancelled' then
    update public.products p set stock = p.stock + a.q
      from (select product_id, sum(qty)::int q from public.order_items where order_id = p_id group by product_id) a
     where p.id::text = a.product_id;
  elsif o.status = 'cancelled' and p_status <> 'cancelled' then
    if exists (select 1 from public.products p
               join (select product_id, sum(qty)::int q from public.order_items where order_id = p_id group by product_id) a
                 on p.id::text = a.product_id where p.stock < a.q) then
      raise exception 'OUT_OF_STOCK';
    end if;
    update public.products p set stock = p.stock - a.q
      from (select product_id, sum(qty)::int q from public.order_items where order_id = p_id group by product_id) a
     where p.id::text = a.product_id;
  end if;
  update public.orders set status = p_status where id = p_id;
end $$;

-- Only customers whose order containing the pair was DELIVERED can review it (one review each, editable).
create or replace function public.submit_review(p_product_id text, p_rating int, p_fit text, p_comment text, p_public_name text)
returns void language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_rating is null or p_rating not between 1 and 5 then raise exception 'BAD_RATING'; end if;
  if p_comment is null or char_length(trim(p_comment)) not between 3 and 1000 then raise exception 'BAD_COMMENT'; end if;
  if p_fit is not null and p_fit not in ('True to size','Runs small','Runs large') then raise exception 'BAD_FIT'; end if;
  if not exists (select 1 from public.orders o join public.order_items i on i.order_id = o.id
                 where o.user_id = v_uid and o.status = 'delivered' and i.product_id = p_product_id) then
    raise exception 'NOT_VERIFIED_BUYER';
  end if;
  insert into public.reviews (product_id, user_id, rating, fit, comment, public_name)
  values (p_product_id, v_uid, p_rating, p_fit, trim(p_comment), left(nullif(trim(p_public_name), ''), 40))
  on conflict (product_id, user_id)
  do update set rating = excluded.rating, fit = excluded.fit, comment = excluded.comment,
                public_name = excluded.public_name, created_at = now();
end $$;

-- Optional housekeeping: cancels orders that stayed 'pending' for too long and returns the stock.
-- Not scheduled by default. To schedule (pg_cron enabled): select cron.schedule('expire-orders','0 * * * *','select public.expire_stale_orders(168)');
create or replace function public.expire_stale_orders(p_hours int default 168) returns int
language plpgsql security definer set search_path = public as $$
declare r record; n int := 0;
begin
  for r in select id from public.orders where status = 'pending' and created_at < now() - make_interval(hours => p_hours) loop
    update public.products p set stock = p.stock + a.q
      from (select product_id, sum(qty)::int q from public.order_items where order_id = r.id group by product_id) a
     where p.id::text = a.product_id;
    update public.orders set status = 'cancelled' where id = r.id;
    n := n + 1;
  end loop;
  return n;
end $$;

