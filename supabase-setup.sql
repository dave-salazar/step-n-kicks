-- Admin = a row in public.admins matching the signed-in user (by id, or by CONFIRMED email).
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admins a join auth.users u on u.id = auth.uid()
    where a.user_id = u.id
       or (a.user_id is null and u.email_confirmed_at is not null and lower(a.email) = lower(u.email))
  );
$$;

