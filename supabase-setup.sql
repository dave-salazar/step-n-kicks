-- ---------- 3. Row Level Security -------------------------------------
-- Remove every old policy on these tables (old ones may be too permissive) ...
do $$ declare r record; begin
  for r in select schemaname, tablename, policyname from pg_policies
           where (schemaname = 'public' and tablename in
                  ('products','orders','order_items','admins','addresses','reviews','stock_alerts','contact_messages'))
              or (schemaname = 'storage' and tablename = 'objects'
                  and (coalesce(qual,'') ilike '%product-images%' or coalesce(with_check,'') ilike '%product-images%'))
  loop
    execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
end $$;

